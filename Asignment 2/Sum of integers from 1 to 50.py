sum = 0 
for i in range(1,51):
    sum = i + sum 
print(f"The sum of integers from 1 to 50 is: {sum}")

'''This program calculates the sum of integers from 1 to 50 by using a for loop.
The loop iterates through each integer from 1 to 50, adding each integer to the variable 'sum'.
Finally, it prints the total sum to the user.'''